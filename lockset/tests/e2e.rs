//! End-to-end against the real `sops` and `age`: no shims.
//!
//! `mise run e2e` installs the pinned tools and sets `LOCKSET_E2E=1`, so a
//! missing or too-old sops fails with a clear message instead of being skipped.
//! Without that variable the suite skips quietly, which keeps `cargo test` on a
//! machine that has no sops.

#![cfg(unix)]

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const MIN_SOPS: (u32, u32) = (3, 13);

fn required() -> bool {
    std::env::var("LOCKSET_E2E").is_ok_and(|value| value == "1")
}

fn find(name: &str) -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|dir| dir.join(name))
        .find(|candidate| candidate.is_file())
}

/// The pinned tools must be present and new enough, and the failure has to say
/// what to do; a skipped e2e run is invisible otherwise.
fn require_tool(name: &str) -> PathBuf {
    match find(name) {
        Some(path) => path,
        None if required() => panic!(
            "{name} is not on PATH; run `mise install` so the pinned tools are available \
             (`mise run e2e` sets this up)"
        ),
        None => {
            eprintln!("skipping: {name} is not on PATH (run `mise install`)");
            PathBuf::from(name)
        }
    }
}

fn sops_version(sops: &Path) -> (u32, u32) {
    let output = Command::new(sops)
        .arg("--version")
        .output()
        .unwrap_or_else(|error| panic!("cannot run {}: {error}", sops.display()));
    let text = String::from_utf8_lossy(&output.stdout);
    parse_version(&text).unwrap_or_else(|| panic!("cannot read the sops version from {text:?}"))
}

fn parse_version(text: &str) -> Option<(u32, u32)> {
    for word in text.split_whitespace() {
        let word = word.trim_matches(|c: char| !c.is_ascii_digit() && c != '.');
        let mut parts = word.split('.');
        if let (Some(major), Some(minor)) = (parts.next(), parts.next()) {
            if let (Ok(major), Ok(minor)) = (major.parse(), minor.parse()) {
                return Some((major, minor));
            }
        }
    }
    None
}

fn temp_repo(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("lockset-e2e-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("secrets")).unwrap();
    dir
}

fn lockset(repo: &Path, args: &[&str], env: &[(&str, &str)]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_lockset"))
        .arg("--repo")
        .arg(repo)
        .args(args)
        .env_remove("LOCKSET_SOPS")
        .env_remove("LOCKSET_CONFIG")
        .env_remove("LOCKSET_CUSTODY")
        .env_remove("LOCKSET_AGE_KEY")
        .envs(env.iter().copied())
        .output()
        .unwrap()
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

/// An age identity generated by the real `age-keygen`, plus its public key.
fn identity(dir: &Path, name: &str) -> (String, String) {
    let path = dir.join(format!("{name}.txt"));
    let status = Command::new(require_tool("age-keygen"))
        .arg("-o")
        .arg(&path)
        .stderr(std::process::Stdio::null())
        .status()
        .expect("age-keygen runs");
    assert!(status.success(), "age-keygen failed");
    let text = std::fs::read_to_string(&path).unwrap();
    let public = text
        .lines()
        .find_map(|line| line.strip_prefix("# public key: "))
        .or_else(|| text.lines().find(|line| line.starts_with("age1")))
        .expect("age-keygen prints the public key")
        .trim()
        .to_owned();
    (path.display().to_string(), public)
}

fn encrypt(dir: &Path, sops: &Path, recipient: &str) {
    std::fs::write(
        dir.join(".sops.yaml"),
        format!(
            "creation_rules:\n  - path_regex: secrets/.*\\.env$\n    age: {recipient} # admin\n"
        ),
    )
    .unwrap();
    std::fs::write(dir.join("secrets/plain.env"), "TOKEN=s3cret\n").unwrap();
    let encrypted = Command::new(sops)
        .args([
            "--encrypt",
            "--age",
            recipient,
            "--input-type",
            "dotenv",
            "--output-type",
            "dotenv",
        ])
        .arg(dir.join("secrets/plain.env"))
        .output()
        .expect("sops encrypts");
    assert!(
        encrypted.status.success(),
        "sops encrypt failed: {}",
        stderr(&encrypted)
    );
    std::fs::write(dir.join("secrets/dev.env"), &encrypted.stdout).unwrap();
    std::fs::remove_file(dir.join("secrets/plain.env")).unwrap();
}

#[test]
fn the_pinned_tools_are_present_and_new_enough() {
    let sops = require_tool("sops");
    if !sops.is_absolute() {
        return;
    }
    let version = sops_version(&sops);
    if required() {
        assert!(
            version >= MIN_SOPS,
            "sops {}.{} is older than the required {}.{}; run `mise install` \
             (mise.toml pins the version)",
            version.0,
            version.1,
            MIN_SOPS.0,
            MIN_SOPS.1
        );
    }
    let _ = require_tool("age-keygen");
}

#[test]
fn a_real_repository_round_trips_through_sops_and_lockset() {
    let sops = require_tool("sops");
    if !sops.is_absolute() {
        return;
    }
    let repo = temp_repo("roundtrip");
    let (key_path, public) = identity(&repo, "admin");
    let key = std::fs::read_to_string(&key_path)
        .unwrap()
        .lines()
        .find(|line| line.starts_with("AGE-SECRET-KEY-1"))
        .unwrap()
        .to_owned();
    encrypt(&repo, &sops, &public);
    let env = [("LOCKSET_AGE_KEY", key.as_str())];

    let status = lockset(&repo, &["status"], &env);
    assert_eq!(status.status.code(), Some(0), "{}", stderr(&status));
    assert!(
        stdout(&status).contains("secrets/dev.env"),
        "{}",
        stdout(&status)
    );

    let doctor = lockset(&repo, &["doctor"], &env);
    assert_eq!(doctor.status.code(), Some(0), "{}", stdout(&doctor));
    assert!(stdout(&doctor).contains("sops "), "{}", stdout(&doctor));

    let run = lockset(
        &repo,
        &[
            "run",
            "--payload",
            "secrets/dev.env",
            "--",
            "sh",
            "-c",
            "test \"$TOKEN\" = s3cret",
        ],
        &env,
    );
    assert_eq!(run.status.code(), Some(0), "{}", stderr(&run));

    // A real write through sops, proven by reading it back through lockset.
    let set = lockset(
        &repo,
        &[
            "set",
            "NEW_KEY",
            "--payload",
            "secrets/dev.env",
            "--from-env",
            "NEW_VALUE",
        ],
        &[
            ("LOCKSET_AGE_KEY", key.as_str()),
            ("NEW_VALUE", "added-by-e2e"),
        ],
    );
    assert_eq!(set.status.code(), Some(0), "{}", stderr(&set));

    let exported = lockset(&repo, &["export", "--payload", "secrets/dev.env"], &env);
    let values = stdout(&exported);
    assert_eq!(exported.status.code(), Some(0), "{}", stderr(&exported));
    assert!(values.contains("TOKEN=s3cret"), "{values}");
    assert!(values.contains("NEW_KEY=added-by-e2e"), "{values}");

    // Rotate the data key, then prove the values still read back.
    let rotate = lockset(&repo, &["rotate", "--all"], &env);
    assert_eq!(rotate.status.code(), Some(0), "{}", stderr(&rotate));
    let reexported = lockset(&repo, &["export", "--payload", "secrets/dev.env"], &env);
    assert!(stdout(&reexported).contains("NEW_KEY=added-by-e2e"));

    // Grant a second real identity and read the payload through it.
    let (_other_path, other_public) = identity(&repo, "reader");
    let grant = lockset(
        &repo,
        &["grant", &other_public, "--label", "dev-reader"],
        &env,
    );
    assert_eq!(grant.status.code(), Some(0), "{}", stderr(&grant));
    let map = std::fs::read_to_string(repo.join(".sops.yaml")).unwrap();
    assert!(map.contains(&other_public), "{map}");

    let _ = std::fs::remove_dir_all(&repo);
}

#[test]
fn an_old_sops_is_refused_with_a_clear_message() {
    // A shim here is deliberate: the point is the version gate, not a real old
    // sops binary.
    let repo = temp_repo("old-sops");
    std::fs::write(
        repo.join(".sops.yaml"),
        "creation_rules:\n  - path_regex: secrets/.*\\.env$\n    age: age1qqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqq\n",
    )
    .unwrap();
    std::fs::write(repo.join("secrets/dev.env"), "TOKEN=ENC[a,type:str]\n").unwrap();
    let shim = repo.join("sops-old");
    std::fs::write(
        &shim,
        "#!/bin/sh\nif [ \"$1\" = \"--version\" ]; then echo 'sops 3.12.0'; exit 0; fi\nexit 1\n",
    )
    .unwrap();
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(&shim, std::fs::Permissions::from_mode(0o755)).unwrap();

    let output = Command::new(env!("CARGO_BIN_EXE_lockset"))
        .arg("--repo")
        .arg(&repo)
        .arg("doctor")
        .env("LOCKSET_SOPS", &shim)
        .env("LOCKSET_AGE_KEY", "AGE-SECRET-KEY-1EXAMPLE")
        .output()
        .unwrap();
    let out = stdout(&output);

    assert_eq!(output.status.code(), Some(1), "{out}");
    assert!(out.contains("older than the required 3.13"), "{out}");
    assert!(out.contains("--sops"), "{out}");

    let _ = std::fs::remove_dir_all(&repo);
}
